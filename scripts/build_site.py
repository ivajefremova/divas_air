"""Assemble the static demo site in site/ (for GitHub Pages or any static host).

Copies the web app, the slim map layers, the simulated cameras and the scenario library (plus the real
replay bundle if module 6 has produced it), and writes a config.js with site-relative paths. Nothing
is generated here: run build_web_layers.py / fake_cameras.py / make_fake_replay.py first if needed.

    python scripts/build_site.py            ->  site/   (test: python -m http.server -d site)
"""

import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from divas_air import config as C  # noqa: E402

WEB = C.ROOT / "app" / "web"
SITE = C.ROOT / "site"
PUBLIC_URL = "https://ivajefremova.github.io/divas_air/"

if __name__ == "__main__":
    if SITE.exists():
        shutil.rmtree(SITE)
    shutil.copytree(WEB, SITE, ignore=shutil.ignore_patterns("config.js", ".DS_Store"))
    shutil.copytree(C.PROCESSED / "demo" / "replay_fake", SITE / "replay_fake", ignore=shutil.ignore_patterns(".DS_Store"))
    real = C.PROCESSED / "demo" / "replay"
    if (real / "manifest.json").exists():
        shutil.copytree(real, SITE / "replay", ignore=shutil.ignore_patterns(".DS_Store"))
    cfg = dict(scenarioIndex="replay_fake/index.json", realBundle="replay/", layers="data/", localTiles="",
               publicUrl=PUBLIC_URL, qr="qr.png")
    (SITE / "config.js").write_text("// Generated by scripts/build_site.py for the published site.\nwindow.DIVAS_CFG = "
                                    + json.dumps(cfg, indent=2) + ";\n")
    (SITE / ".nojekyll").write_text("")
    size = sum(f.stat().st_size for f in SITE.rglob("*") if f.is_file()) / 1e6
    print(f"site/ ready: {sum(1 for f in SITE.rglob('*') if f.is_file())} files, {size:.1f} MB -> {PUBLIC_URL}")
